--[[ Crimson-Police · built-in mission
  Street Race Bust · street_race_bust · Patrol · 1-2 officers · 2 stars · 4 min race · cooldown 15 min
  Three NPC racers (scales) in sports cars lap a 2-3 km street loop. Stop them (below 5 km/h for
  5 s), then "Detain driver" (3 s). Completed when every racer is detained, or when the race ends
  with at least one detained. +30 per racer detained, +20 more for all of them; ramming a racer
  at over 100 km/h -10 each. Boxing racers in means contact, so no heavy-damage penalty.
  Loops, stored as the route recorder stores them: road waypoints on the GTA vehicle-node network
  at every junction or turn and at least every 100 m, in race direction, loop = true, the last
  waypoint 40-49 m before the first. Little Seoul (San Andreas Ave, South Rockford Dr, Calais Ave),
  La Mesa (Popular St, Innocence Blvd, El Rancho Blvd, Vespucci Blvd), Mirror Park (Popular St,
  Glory Way, Mirror Park Blvd, East Mirror Dr, San Andreas Ave, Supply St), Downtown Vinewood
  (Power St, Vinewood Blvd, Elgin Ave, Clinton Ave, Las Lagunas Blvd, Occupation Ave) and
  Davis & Rancho (Davis Ave, Innocence Blvd, Roy Lowenstein Blvd, Dutch London St, Autopia Pkwy).
  Blocks: pursuit (mode = 'stop', route = location.route, spawns = location.spawns).
  Start: an intercept waypoint on the loop, about half way round (radius 60 m); the race starts when
  the first participant arrives, with the racers leaving a grid up the loop 150-310 m from the intercept:
  inside OneSync's 424 m range of an officer anywhere in the circle, so the racers are streamed, owned and
  driving from the first second. 8 grid slots per loop: enough for the Critical tier (3 x 2.5).
]]

